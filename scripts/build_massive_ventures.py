def generate_full_database():
    print(f"Base curated investments count: {len(INVESTMENTS)}")

    existing_path = os.path.join(os.path.dirname(__file__), '..', 'data', 'ventures.json')
    if os.path.exists(existing_path):
        with open(existing_path, 'r', encoding='utf-8') as f:
            existing_data = json.load(f)
        existing_list = existing_data.get('investments', [])
        print(f"Loaded {len(existing_list)} existing investments from ventures.json")
    else:
        existing_list = []

    existing_map = {}
    for inv in existing_list:
        key = (inv.get('investor_company', '').strip().lower(), inv.get('startup_name', '').strip().lower())
        existing_map[key] = inv

    curated_keys = set()
    for inv in INVESTMENTS:
        key = (inv.get('investor_company', '').strip().lower(), inv.get('startup_name', '').strip().lower())
        curated_keys.add(key)

    def derive_tech_tag(startup_name, sector, desc):
        text = (startup_name + " " + desc).lower()
        if "photon" in text or "광" in text or "laser" in text or "pic" in text or "optical" in text:
            return "광인터커넥트"
        elif "chiplet" in text or "칩렛" in text or "d2d" in text or "die" in text:
            return "칩렛 D2D"
        elif "risc-v" in text or "riscv" in text:
            return "RISC-V 코어"
        elif "cxl" in text:
            return "CXL 메모리"
        elif "quantum" in text or "양자" in text:
            return "양자컴퓨팅"
        elif "robot" in text or "로봇" in text or "humanoid" in text:
            return "휴머노이드 AI"
        elif "power" in text or "sic" in text or "gan" in text or "전력" in text:
            return "전력반도체 SiC"
        elif "sensor" in text or "radar" in text or "lidar" in text or "라이다" in text or "레이더" in text or "센서" in text:
            return "차량 센서"
        elif "eda" in text or "설계" in text or "ip" in text:
            return "EDA 및 IP"
        elif "edge" in text or "엣지" in text or "npu" in text:
            return "Edge AI NPU"
        elif "npu" in text or "accelerator" in text or "가속" in text or "llm" in text:
            return "AI 가속기"
        else:
            return "반도체 딥테크"

