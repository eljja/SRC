"""
scripts/remediate_dataset.py

SRC Observatory Data Remediation & Verification Tool
=====================================================
Remediates synthetic funding amounts, ungrounded company/category fallbacks,
and arbitrary 3-year durations across data/collaborations.json.

Guarantees:
- Idempotency: Multiple executions yield identical output without double-wrapping.
- Rollback: Reversible via --rollback using data/collaborations.backup.json or _audit_history.
- Preservation: Contaminated past values are archived in _audit_history, not discarded.
- Separation of Concerns: Distinguishes 'unverified' funding from 'none_stated' (Nil/None) and 'amount_0'.
- Quarantine: Places non-semiconductor (medical, orthopedic, dental, etc.) studies in quarantined status.

CLI Modes:
  python scripts/remediate_dataset.py --dry-run
  python scripts/remediate_dataset.py --dry-run --report reports/dry_run_remediation_report.md
  python scripts/remediate_dataset.py --apply
  python scripts/remediate_dataset.py --rollback
"""

